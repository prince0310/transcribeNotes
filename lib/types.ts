export interface NoteSection {
  heading: string;
  timestamp: string;
  summary: string;
  points: string[];
}

export interface Infographic {
  headline: string;
  tagline: string;
  stats: { value: string; label: string }[];
  pillars: { emoji: string; title: string; text: string }[];
  flow: string[];
  bottomLine: string;
}

export interface Notes {
  title: string;
  subtitle: string;
  summary: string;
  keyTakeaways: string[];
  sections: NoteSection[];
  definitions: { term: string; meaning: string }[];
  actionItems: string[];
  quote: string;
  infographic: Infographic;
  /** Layout + exact text for the AI-drawn infographic (only when that style is chosen). */
  imageBrief: string;
}

export interface TranscriptResult {
  videoId: string;
  url: string;
  title: string;
  author: string;
  language: string;
  source: "captions" | "gemini";
  autoGenerated: boolean;
  text: string;
  wordCount: number;
  note?: string;
}

export type Detail = "concise" | "detailed";

export type Format = "text" | "pdf" | "infographic";

/** gemini/openai: drawn by an image model from Gemini's brief; template: rendered locally. */
export type InfographicStyle = "gemini" | "openai" | "template";

export type StepId = "transcript" | "notes" | "design";
export type StepStatus = "idle" | "active" | "done" | "error";
export interface StepState {
  status: StepStatus;
  detail: string;
  startedAt?: number;
  endedAt?: number;
}
