// Server-side transcript retrieval: YouTube captions first, Gemini video understanding as fallback.
import { fmtTime, watchUrl } from "./youtube-id";
import { geminiGenerate } from "./gemini";

interface Segment {
  start: number;
  text: string;
}
interface CaptionTrack {
  baseUrl: string;
  languageCode: string;
  kind?: string;
}

const ANDROID_VERSION = "20.10.38";
const ANDROID_UA = `com.google.android.youtube/${ANDROID_VERSION} (Linux; U; Android 14) gzip`;

export async function fetchVideoMeta(videoId: string): Promise<{ title?: string; author?: string }> {
  try {
    const r = await fetch(
      `https://www.youtube.com/oembed?format=json&url=${encodeURIComponent(watchUrl(videoId))}`,
      { cache: "no-store" },
    );
    if (!r.ok) return {};
    const j = await r.json();
    return { title: j.title, author: j.author_name };
  } catch {
    return {};
  }
}

function decodeEntities(s: string): string {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&");
}

const cleanText = (s: string) =>
  decodeEntities(decodeEntities(s.replace(/<[^>]+>/g, "")))
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .trim();

function parseCaptionXml(xml: string): Segment[] {
  const out: Segment[] = [];
  let m: RegExpExecArray | null;
  const classic = /<text start="([\d.]+)"[^>]*>([\s\S]*?)<\/text>/g;
  while ((m = classic.exec(xml))) out.push({ start: parseFloat(m[1]), text: cleanText(m[2]) });
  if (!out.length) {
    const srv3 = /<p t="(\d+)"[^>]*>([\s\S]*?)<\/p>/g;
    while ((m = srv3.exec(xml))) out.push({ start: Number(m[1]) / 1000, text: cleanText(m[2]) });
  }
  return out.filter((s) => s.text && !/^\[(music|applause|laughter)\]$/i.test(s.text));
}

function pickTrack(tracks: CaptionTrack[]): CaptionTrack {
  const manual = tracks.filter((t) => t.kind !== "asr");
  const en = (t: CaptionTrack) => t.languageCode.toLowerCase().startsWith("en");
  return manual.find(en) ?? manual[0] ?? tracks.find(en) ?? tracks[0];
}

/** Groups caption lines into ~45s paragraphs prefixed with [m:ss] so the notes can cite timestamps. */
function segmentsToText(segs: Segment[]): string {
  const paras: { start: number; parts: string[] }[] = [];
  for (const s of segs) {
    const cur = paras[paras.length - 1];
    if (!cur || s.start - cur.start >= 45) paras.push({ start: s.start, parts: [s.text] });
    else cur.parts.push(s.text);
  }
  return paras.map((p) => `[${fmtTime(p.start)}] ${p.parts.join(" ")}`).join("\n\n");
}

export async function fetchCaptions(videoId: string) {
  const res = await fetch("https://www.youtube.com/youtubei/v1/player?prettyPrint=false", {
    method: "POST",
    headers: { "Content-Type": "application/json", "User-Agent": ANDROID_UA },
    body: JSON.stringify({
      context: {
        client: { clientName: "ANDROID", clientVersion: ANDROID_VERSION, androidSdkVersion: 34, hl: "en" },
      },
      videoId,
    }),
    cache: "no-store",
  });
  if (!res.ok) throw new Error(`YouTube responded ${res.status}`);
  const data = await res.json();

  const ps = data?.playabilityStatus;
  if (ps?.status && ps.status !== "OK") throw new Error(ps.reason || `video is ${String(ps.status).toLowerCase()}`);

  const tracks: CaptionTrack[] = data?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  if (!tracks.length) throw new Error("no captions on this video");

  const track = pickTrack(tracks);
  const url = track.baseUrl.replace(/&fmt=[^&]*/, "");
  const xml = await (await fetch(url, { headers: { "User-Agent": ANDROID_UA }, cache: "no-store" })).text();
  const segments = parseCaptionXml(xml);
  if (!segments.length) throw new Error("caption track was empty");

  return {
    text: segmentsToText(segments),
    language: track.languageCode,
    autoGenerated: track.kind === "asr",
    title: data?.videoDetails?.title as string | undefined,
    author: data?.videoDetails?.author as string | undefined,
  };
}

const TRANSCRIBE_PROMPT = `Transcribe the spoken content of this video as accurately as possible.
Rules:
- Output ONLY the transcript, no commentary or headings.
- Split it into paragraphs of roughly 30-60 seconds.
- Start every paragraph with its start time in square brackets, e.g. [0:00], [1:35], [1:02:10].
- Keep the original spoken language. Omit filler sounds like "um" and "uh".`;

export async function transcribeWithGemini(apiKey: string, model: string, videoId: string) {
  const text = await geminiGenerate({
    apiKey,
    model,
    contents: [
      {
        role: "user",
        parts: [{ fileData: { fileUri: watchUrl(videoId) } }, { text: TRANSCRIBE_PROMPT }],
      },
    ],
    generationConfig: { temperature: 0.1, mediaResolution: "MEDIA_RESOLUTION_LOW" },
  });
  return text.trim();
}
