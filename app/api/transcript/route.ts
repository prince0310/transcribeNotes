import { NextRequest, NextResponse } from "next/server";
import { extractVideoId, watchUrl } from "@/lib/youtube-id";
import { fetchCaptions, fetchVideoMeta, transcribeWithGemini } from "@/lib/youtube";
import type { TranscriptResult } from "@/lib/types";

export const runtime = "nodejs";
// Gemini transcription of long videos can take a while.
export const maxDuration = 300;

const words = (t: string) => t.replace(/\[[\d:]+\]/g, "").split(/\s+/).filter(Boolean).length;

export async function POST(req: NextRequest) {
  const body = await req.json().catch(() => ({}));
  const apiKey = req.headers.get("x-gemini-key")?.trim() ?? "";
  const model = String(body.model ?? "");
  const videoId = extractVideoId(String(body.url ?? ""));
  if (!videoId) {
    return NextResponse.json({ error: "That doesn't look like a valid YouTube link." }, { status: 400 });
  }

  const meta = await fetchVideoMeta(videoId);
  const base = { videoId, url: watchUrl(videoId) };

  // 1) Fast path: the video's own captions.
  let captionError = "";
  try {
    const cap = await fetchCaptions(videoId);
    const result: TranscriptResult = {
      ...base,
      title: meta.title || cap.title || "Untitled video",
      author: meta.author || cap.author || "",
      language: cap.language,
      source: "captions",
      autoGenerated: cap.autoGenerated,
      text: cap.text,
      wordCount: words(cap.text),
    };
    return NextResponse.json(result);
  } catch (e) {
    captionError = (e as Error).message;
  }

  // 2) Fallback: let Gemini watch the video and transcribe it.
  if (!apiKey) {
    return NextResponse.json({ error: `Couldn't read captions (${captionError}).` }, { status: 502 });
  }
  try {
    const text = await transcribeWithGemini(apiKey, model, videoId);
    const result: TranscriptResult = {
      ...base,
      title: meta.title || "Untitled video",
      author: meta.author || "",
      language: "auto",
      source: "gemini",
      autoGenerated: true,
      text,
      wordCount: words(text),
      note: `Captions unavailable (${captionError}), so Gemini transcribed the video.`,
    };
    return NextResponse.json(result);
  } catch (e) {
    return NextResponse.json(
      {
        error: `Couldn't get a transcript. Captions: ${captionError}. Gemini: ${(e as Error).message} (the video must be public).`,
      },
      { status: 502 },
    );
  }
}
