"use client";
import { useMemo, useState } from "react";
import {
  Check,
  Copy,
  Download,
  FileText,
  FileType2,
  Image as ImageIcon,
  Loader2,
  RefreshCw,
  ScrollText,
  ExternalLink,
} from "lucide-react";
import NotesDocument from "./NotesDocument";
import type { Format, Notes, TranscriptResult } from "@/lib/types";
import { saveBlob, slugify, textBlob, toMarkdown, toPlainText } from "@/lib/exporters";
import { thumbUrl } from "@/lib/youtube-id";

export interface Assets {
  pdf?: Blob;
  png?: Blob;
  pdfUrl?: string;
  pngUrl?: string;
  error?: string;
}

type Tab = "notes" | "pdf" | "infographic" | "transcript";

export default function Results({
  transcript: t,
  notes,
  assets,
  formats,
  onRedraw,
  redrawing,
}: {
  transcript: TranscriptResult;
  notes: Notes;
  assets: Assets;
  formats: Format[];
  /** Present when the infographic is AI-drawn: draws a fresh version. */
  onRedraw?: () => void;
  redrawing?: boolean;
}) {
  const has = (f: Format) => formats.includes(f);
  const [tab, setTab] = useState<Tab>(has("text") ? "notes" : has("pdf") ? "pdf" : has("infographic") ? "infographic" : "transcript");
  const [copied, setCopied] = useState(false);
  const base = slugify(notes.title);
  const md = useMemo(() => toMarkdown(notes, t), [notes, t]);

  const dl = {
    md: () => saveBlob(textBlob(md, "text/markdown"), `${base}.md`),
    txt: () => saveBlob(textBlob(toPlainText(notes, t)), `${base}.txt`),
    pdf: () => assets.pdf && saveBlob(assets.pdf, `${base}.pdf`),
    png: () => assets.png && saveBlob(assets.png, `${base}-infographic.png`),
    transcript: () => saveBlob(textBlob(`${t.title}\n${t.url}\n\n${t.text}`), `${base}-transcript.txt`),
  };

  const copy = async () => {
    await navigator.clipboard.writeText(md);
    setCopied(true);
    setTimeout(() => setCopied(false), 1600);
  };

  const tabs = (
    [
      { id: "notes", label: "Notes", icon: FileText, show: has("text") },
      { id: "pdf", label: "PDF", icon: FileType2, show: has("pdf") },
      { id: "infographic", label: "Infographic", icon: ImageIcon, show: has("infographic") },
      { id: "transcript", label: "Transcript", icon: ScrollText, show: true },
    ] as { id: Tab; label: string; icon: typeof FileText; show: boolean }[]
  ).filter((x) => x.show);

  return (
    <section className="rise space-y-6">
      {/* Video + quick downloads */}
      <div className="glass flex flex-col gap-5 rounded-3xl p-5 sm:p-6 lg:flex-row lg:items-center">
        <a href={t.url} target="_blank" rel="noreferrer" className="group flex min-w-0 flex-1 items-center gap-4">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={thumbUrl(t.videoId)} alt="" className="h-20 w-36 shrink-0 rounded-xl object-cover ring-1 ring-white/10" />
          <div className="min-w-0">
            <div className="truncate font-semibold text-white group-hover:underline">{t.title}</div>
            <div className="mt-0.5 truncate text-sm text-slate-400">{t.author}</div>
            <div className="mt-2 flex flex-wrap gap-1.5 text-[11px]">
              <Chip>{t.source === "captions" ? (t.autoGenerated ? "Auto captions" : "Official captions") : "Gemini transcription"}</Chip>
              <Chip>{t.wordCount.toLocaleString()} words</Chip>
              <Chip>{notes.sections.length} sections</Chip>
            </div>
          </div>
        </a>
        <div
          className="grid gap-2 lg:w-[420px]"
          style={{ gridTemplateColumns: `repeat(${formats.length || 1}, minmax(0, 1fr))` }}
        >
          {has("text") && <QuickDl label="Text" sub=".md" icon={FileText} onClick={dl.md} />}
          {has("pdf") && (
            <QuickDl label="PDF" sub=".pdf" icon={FileType2} onClick={dl.pdf} loading={!assets.pdf && !assets.error} />
          )}
          {has("infographic") && (
            <QuickDl label="Infographic" sub=".png" icon={ImageIcon} onClick={dl.png} loading={!assets.png && !assets.error} />
          )}
        </div>
      </div>
      {t.note && <p className="text-center text-xs text-amber-200/80">{t.note}</p>}
      {assets.error && (
        <p className="rounded-2xl bg-rose-500/10 px-4 py-3 text-center text-sm text-rose-200">{assets.error}</p>
      )}

      {/* Tabs */}
      <div className="glass rounded-3xl p-2 sm:p-3">
        <div className="flex gap-1 overflow-x-auto p-1 scroll-thin" role="tablist">
          {tabs.map(({ id, label, icon: Icon }) => (
            <button
              key={id}
              role="tab"
              aria-selected={tab === id}
              onClick={() => setTab(id)}
              className={`flex shrink-0 items-center gap-2 rounded-2xl px-4 py-2.5 text-sm font-medium transition ${
                tab === id
                  ? "bg-gradient-to-r from-indigo-500/30 to-fuchsia-500/30 text-white ring-1 ring-white/15"
                  : "text-slate-400 hover:bg-white/5 hover:text-white"
              }`}
            >
              <Icon className="h-4 w-4" />
              {label}
            </button>
          ))}
        </div>

        <div className="p-2 pt-4 sm:p-4">
          {tab === "notes" && (
            <Panel
              actions={
                <>
                  <Btn onClick={copy} icon={copied ? Check : Copy}>{copied ? "Copied" : "Copy"}</Btn>
                  <Btn onClick={dl.txt} icon={Download}>.txt</Btn>
                  <Btn onClick={dl.md} icon={Download} primary>Markdown</Btn>
                </>
              }
            >
              <div className="mx-auto max-w-[820px]">
                <NotesDocument notes={notes} meta={t} />
              </div>
            </Panel>
          )}

          {tab === "pdf" && (
            <Panel
              actions={
                <>
                  {assets.pdfUrl && (
                    <Btn onClick={() => window.open(assets.pdfUrl, "_blank")} icon={ExternalLink}>Open</Btn>
                  )}
                  <Btn onClick={dl.pdf} icon={Download} primary disabled={!assets.pdf}>Download PDF</Btn>
                </>
              }
            >
              {assets.pdfUrl ? (
                <iframe
                  src={`${assets.pdfUrl}#view=FitH`}
                  title="PDF preview"
                  className="h-[78vh] w-full rounded-2xl border border-white/10 bg-white"
                />
              ) : (
                <Building what="PDF" />
              )}
            </Panel>
          )}

          {tab === "infographic" && (
            <Panel
              actions={
                <>
                  {onRedraw && (
                    <Btn onClick={onRedraw} icon={redrawing ? Loader2 : RefreshCw} disabled={redrawing}>
                      {redrawing ? "Drawing…" : "Redraw"}
                    </Btn>
                  )}
                  <Btn onClick={dl.png} icon={Download} primary disabled={!assets.png || redrawing}>Download PNG</Btn>
                </>
              }
            >
              {assets.pngUrl && !redrawing ? (
                // eslint-disable-next-line @next/next/no-img-element
                <img
                  src={assets.pngUrl}
                  alt="Infographic"
                  className={`mx-auto w-full rounded-2xl shadow-2xl ring-1 ring-white/10 ${onRedraw ? "max-w-[1400px]" : "max-w-[760px]"}`}
                />
              ) : (
                <Building what={onRedraw ? "infographic — the image model usually takes 1–2 minutes" : "infographic"} />
              )}
            </Panel>
          )}

          {tab === "transcript" && (
            <Panel actions={<Btn onClick={dl.transcript} icon={Download} primary>Transcript .txt</Btn>}>
              <pre className="scroll-thin max-h-[70vh] overflow-auto whitespace-pre-wrap rounded-2xl border border-white/10 bg-black/30 p-5 font-sans text-sm leading-7 text-slate-300">
                {t.text}
              </pre>
            </Panel>
          )}
        </div>
      </div>
    </section>
  );
}

function Panel({ actions, children }: { actions: React.ReactNode; children: React.ReactNode }) {
  return (
    <div>
      <div className="mb-4 flex flex-wrap justify-end gap-2">{actions}</div>
      {children}
    </div>
  );
}

function Btn({
  children,
  onClick,
  icon: Icon,
  primary,
  disabled,
}: {
  children: React.ReactNode;
  onClick: () => void;
  icon: typeof Download;
  primary?: boolean;
  disabled?: boolean;
}) {
  return (
    <button
      onClick={onClick}
      disabled={disabled}
      className={`inline-flex h-10 items-center gap-2 rounded-xl px-4 text-sm font-medium transition disabled:cursor-not-allowed disabled:opacity-40 ${
        primary ? "btn-primary text-white" : "bg-white/8 text-slate-200 ring-1 ring-white/10 hover:bg-white/12"
      }`}
    >
      <Icon className="h-4 w-4" />
      {children}
    </button>
  );
}

function QuickDl({
  label,
  sub,
  icon: Icon,
  onClick,
  loading,
}: {
  label: string;
  sub: string;
  icon: typeof Download;
  onClick: () => void;
  loading?: boolean;
}) {
  return (
    <button
      onClick={onClick}
      disabled={loading}
      className="group flex flex-col items-center gap-1 rounded-2xl border border-white/10 bg-white/[0.04] px-2 py-3 transition hover:border-fuchsia-400/40 hover:bg-fuchsia-500/10 disabled:opacity-50"
    >
      {loading ? (
        <Loader2 className="h-5 w-5 animate-spin text-slate-400" />
      ) : (
        <Icon className="h-5 w-5 text-fuchsia-300 transition group-hover:scale-110" />
      )}
      <span className="text-xs font-semibold text-white">{label}</span>
      <span className="flex items-center gap-1 text-[10px] text-slate-400">
        <Download className="h-3 w-3" /> {sub}
      </span>
    </button>
  );
}

function Chip({ children }: { children: React.ReactNode }) {
  return <span className="rounded-full bg-white/8 px-2.5 py-0.5 text-slate-300 ring-1 ring-white/10">{children}</span>;
}

function Building({ what }: { what: string }) {
  return (
    <div className="flex h-72 flex-col items-center justify-center gap-3 rounded-2xl border border-dashed border-white/10 text-sm text-slate-400">
      <Loader2 className="h-6 w-6 animate-spin text-fuchsia-300" />
      Designing your {what}…
    </div>
  );
}
